#!/usr/bin/env python3
"""Prototype BC7 keycaps before embedding them in the Mac launcher."""
from pathlib import Path
import ctypes
import struct
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_controller_overlays import entries, plain
from inspect_button_atlas import deswizzle, swizzle


def keycap(label):
    # The game's BC7 button shader expects the red/blue channels fixed near 123,
    # green for the pale key surface, and alpha for its dark outline and glyph.
    im = Image.new('RGBA', (64, 64), (123, 0, 123, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((6, 3, 57, 57), radius=8, fill=(123, 255, 123, 223), outline=(123, 165, 123, 158), width=3)
    ink = (123, 255, 123, 0)
    if label == '↵':
        d.line(((44, 19), (44, 37), (20, 37)), fill=ink, width=5, joint='curve')
        d.polygon(((17, 37), (29, 28), (29, 46)), fill=ink)
    else:
        font = ImageFont.truetype('/System/Library/Fonts/Supplemental/Arial.ttf', 28 if len(label) <= 2 else 21)
        box = d.textbbox((0, 0), label, font=font)
        d.text(((64 - (box[2] - box[0])) / 2 - box[0], (64 - (box[3] - box[1])) / 2 - box[1]), label, fill=ink, font=font)
    return im


codec = ctypes.CDLL(str(Path('local-data/feature-build/libbc7enc16.dylib').resolve()))
codec.encode_bc7_block.argtypes = [ctypes.c_void_p, ctypes.c_void_p]


def encode_block(pixels):
    data = (ctypes.c_uint8 * 64)(*(c for p in pixels for c in p))
    out = (ctypes.c_uint8 * 16)()
    codec.encode_bc7_block(out, data)
    return bytes(out)


def encode(image):
    px = image.load()
    return b''.join(encode_block([px[x + u, y + v] for v in range(4) for u in range(4)])
                    for y in range(0, 64, 4) for x in range(0, 64, 4))


def build(source, target):
    arc = source.read_bytes()
    cat = entries(arc)
    e = next(x for x in cat if x[1].endswith('\\button_swi_00_ID_HQ'))
    tex = plain(e[2], e[3])
    blocks = bytearray(deswizzle(tex))
    for dest_col, label in ((0, 'Tab'), (1, '↵')):
        data = encode(keycap(label))
        for row in range(16):
            offset = ((2 * 16 + row) * 128 + dest_col * 16) * 16
            blocks[offset:offset + 256] = data[row * 256:(row + 1) * 256]
    new = tex[:24] + swizzle(blocks)
    packed = zlib.compress(new)
    out = bytearray(arc)
    struct.pack_into('<III', out, e[0] + 0x84, len(packed), e[4] | len(new), len(out))
    out.extend(packed)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(out)


def write_header(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ['// BC7 64x64 keycaps generated by scripts/probe_generated_keycaps.py.',
             '// The in-game font lacks native Return, Tab and Escape keycaps.',
             '#pragma once']
    for name, label in (('return', '↵'), ('tab', 'Tab'), ('escape', 'Esc')):
        data = encode(keycap(label))
        lines.append(f'static const unsigned char button_keycap_{name}[{len(data)}] = {{')
        for i in range(0, len(data), 24):
            lines.append('    ' + ', '.join(f'0x{x:02x}' for x in data[i:i + 24]) + ',')
        lines.append('};')
    path.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    root = Path(sys.argv[1])
    out = Path(sys.argv[2])
    if len(sys.argv) > 3: write_header(Path(sys.argv[3]))
    for lang in ('jpn', 'eng'):
        build(root / f'font_{lang}.arc', out / 'nativeNXx64/archive' / f'font_{lang}.arc')
